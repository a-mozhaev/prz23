#!/bin/bash
# Скрипт для установки и запуска проекта Калькулятор
# Автор: Можаев А.В.

set -e

echo "=========================================="
echo "   Установка и запуск проекта Калькулятор"
echo "=========================================="

# Переход в папку скрипта (для запуска из любой директории)
cd "$(dirname "$0")" || exit 1

# Создание и активация виртуального окружения
echo "[1/4] Проверка виртуального окружения..."
if [ ! -d "venv" ]; then
    echo "Виртуальное окружение не найдено. Создаём..."
    if ! command -v python3.11 >/dev/null 2>&1; then
        echo "ОШИБКА: Python 3.11 не найден!"
        exit 1
    fi
    python3.11 -m venv venv
else
    echo "Виртуальное окружение уже существует."
fi

if [ ! -f "venv/bin/activate" ]; then
    echo "ОШИБКА: Виртуальное окружение повреждено или создано неправильно!"
    exit 1
fi
source venv/bin/activate

# Установка зависимостей
echo "[2/4] Установка зависимостей..."
if [ ! -f "requirements.txt" ]; then
    echo "ОШИБКА: Файл requirements.txt не найден!"
    exit 1
fi
python -m pip install -r requirements.txt

# Инициализация базы данных SQLite
echo "[3/4] Инициализация базы данных..."
python -c "import db_manager; db_manager.init_db()"
echo "База данных готова."

# Запуск программы
echo "[4/4] Запуск калькулятора..."
echo "=========================================="
python main.py

# Деактивация окружения после завершения
deactivate
echo "=========================================="
echo "   Программа завершена"
echo "=========================================="
